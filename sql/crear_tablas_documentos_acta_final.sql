CREATE TABLE INV_ACTA_FINAL_DESCARGA_TBL (
    DESCARGA_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTA_FINAL_ID   NUMBER NOT NULL,
    CENTRO          VARCHAR2(100) NOT NULL,
    ALMACEN         VARCHAR2(100) NOT NULL,
    CEDULA_USUARIO  VARCHAR2(30) NOT NULL,
    NOMBRE_USUARIO  VARCHAR2(200),
    PERFIL          VARCHAR2(100),
    DIRECCION_IP    VARCHAR2(64),
    FECHA_DESCARGA  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_INV_AF_DESCARGA_ACTA
    ON INV_ACTA_FINAL_DESCARGA_TBL (ACTA_FINAL_ID, FECHA_DESCARGA);

COMMENT ON TABLE INV_ACTA_FINAL_DESCARGA_TBL IS
    'Auditoria de descargas de actas finales realizadas por la tienda';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.DESCARGA_ID IS 'Identificador de la descarga';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.ACTA_FINAL_ID IS
    'Identificador del acta final, sin FK para conservar la evidencia';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.CENTRO IS 'Centro obtenido de los conteos del acta';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.ALMACEN IS 'Almacen obtenido de los conteos del acta';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.CEDULA_USUARIO IS 'Cedula del usuario que descargo';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.NOMBRE_USUARIO IS 'Nombre del usuario que descargo';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.PERFIL IS 'Perfil activo durante la descarga';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.DIRECCION_IP IS 'Direccion IP informada por la solicitud';
COMMENT ON COLUMN INV_ACTA_FINAL_DESCARGA_TBL.FECHA_DESCARGA IS 'Fecha y hora de la descarga';

CREATE TABLE INV_ACTA_FINAL_DOCUMENTO_TBL (
    DOCUMENTO_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTA_FINAL_ID   NUMBER NOT NULL,
    TIPO_DOCUMENTO  VARCHAR2(20) NOT NULL
                    CHECK (TIPO_DOCUMENTO IN ('ACTA_FIRMADA', 'DENUNCIA')),
    ESTADO          VARCHAR2(20) DEFAULT 'VIGENTE' NOT NULL
                    CHECK (ESTADO IN ('VIGENTE', 'REEMPLAZADO')),
    NOMBRE_ORIGINAL VARCHAR2(255) NOT NULL,
    RUTA_RELATIVA   VARCHAR2(500) NOT NULL,
    TAMANO_BYTES    NUMBER NOT NULL,
    HASH_SHA256     VARCHAR2(64) NOT NULL,
    CENTRO          VARCHAR2(100) NOT NULL,
    ALMACEN         VARCHAR2(100) NOT NULL,
    CEDULA_USUARIO  VARCHAR2(30) NOT NULL,
    NOMBRE_USUARIO  VARCHAR2(200),
    FECHA_CARGA     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_INV_AF_DOC_ACTA
    ON INV_ACTA_FINAL_DOCUMENTO_TBL (ACTA_FINAL_ID, TIPO_DOCUMENTO, ESTADO);

COMMENT ON TABLE INV_ACTA_FINAL_DOCUMENTO_TBL IS
    'Documentos cargados por la tienda para un acta final';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.DOCUMENTO_ID IS 'Identificador del documento';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.ACTA_FINAL_ID IS
    'Identificador del acta final, sin FK para conservar la evidencia';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.TIPO_DOCUMENTO IS
    'ACTA_FIRMADA o DENUNCIA; ambos documentos son obligatorios';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.ESTADO IS
    'VIGENTE para la version actual o REEMPLAZADO para el historial';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.NOMBRE_ORIGINAL IS 'Nombre informado por el usuario';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.RUTA_RELATIVA IS 'Ruta dentro del directorio protegido';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.TAMANO_BYTES IS 'Tamano real del archivo';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.HASH_SHA256 IS 'Hash SHA-256 del contenido';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.CENTRO IS 'Centro obtenido de los conteos del acta';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.ALMACEN IS 'Almacen obtenido de los conteos del acta';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.CEDULA_USUARIO IS 'Cedula del usuario que cargo';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.NOMBRE_USUARIO IS 'Nombre del usuario que cargo';
COMMENT ON COLUMN INV_ACTA_FINAL_DOCUMENTO_TBL.FECHA_CARGA IS 'Fecha y hora de la carga';
